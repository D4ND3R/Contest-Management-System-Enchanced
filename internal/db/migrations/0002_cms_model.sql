-- Tables, columns, defaults and constraints are those of a fresh CMS
-- installation, with the same constraint names (PostgreSQL derives most of
-- them: <table>_pkey, <table>_<columns>_key, <table>_<columns>_fkey,
-- <table>_<column>_check, <table>_check[N]). Differences (DECISIONS.md):
--
--   * ids are identity columns, GENERATED BY DEFAULT so that a dump import
--     keeps the original ids (the importer must setval the sequences);
--   * DateTime columns are timestamptz (CMS stored naive UTC timestamps);
--   * the CMS domains CODENAME, FILENAME, FILENAME_SCHEMA,
--     FILENAME_SCHEMA_ARRAY and DIGEST, and its enum types, are CHECK
--     constraints on text columns: sqlc does not understand domains, and a
--     CHECK is easier to evolve than an enum type;
--   * digests are SHA-256 (64 hex digits) instead of SHA-1; "x" is still
--     the tombstone of a deleted file that can be regenerated (executables,
--     cmsCleanFiles --tombstone);
--   * file contents live in the blob store: there is no fsobjects table;
--   * the defaults that CMS kept in Python are column defaults;
--   * tasks.fk_active_dataset_id: ON UPDATE CASCADE instead of CMS's
--     SET NULL, which also nulled tasks.id and so made renumbering a task
--     or its active dataset fail; no ON DELETE action (NO ACTION) instead
--     of CMS's SET NULL, which failed the same way: as in CMS, the active
--     dataset cannot be deleted (another one must be made live first);
--   * an index that CMS declared on a column already covered by a primary
--     key or UNIQUE constraint starting with that column is not duplicated;
--   * fork additions are marked "Fork addition".
--
-- The CHECK patterns below repeat these CMS domains:
--   codename        ~ '^[A-Za-z0-9_-]+$'
--   filename        ~ '^[A-Za-z0-9_.-]+$' and not '.' or '..'
--   filename schema ~ '^[A-Za-z0-9_.-]+(.%l)?$' and not '.' or '..'
--                   (the unescaped dot is CMS's; kept so that every value
--                   CMS accepts is accepted)
--   digest          ~ '^([0-9a-f]{64}|x)$'

-- People who can log in the administration (cms/db/admin.py). An enabled
-- admin can read everything; the permission bits allow changes.
CREATE TABLE admins (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 text NOT NULL,
    username             text NOT NULL UNIQUE CHECK (username ~ '^[A-Za-z0-9_-]+$'),
    -- "<method>:<string>": "bcrypt:$2b$…" or "plaintext:…".
    authentication       text NOT NULL,
    enabled              boolean NOT NULL DEFAULT true,
    permission_all       boolean NOT NULL DEFAULT false,
    permission_messaging boolean NOT NULL DEFAULT false,
    -- Fork addition: the problem preparer role, who can create and edit
    -- tasks, datasets and their files. An admin without any permission bit
    -- is read-only.
    permission_tasks     boolean NOT NULL DEFAULT false
);

-- A contest: one day of a competition (cms/db/contest.py). Its times live
-- in its groups; main_group_id is the default group.
CREATE TABLE contests (
    id                              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                            text NOT NULL UNIQUE CHECK (name ~ '^[A-Za-z0-9_-]+$'),
    description                     text NOT NULL,
    -- Language codes of the allowed interface localizations (empty = all).
    allowed_localizations           text[] NOT NULL DEFAULT '{}',
    -- Names of the programming languages allowed in the contest.
    languages                       text[] NOT NULL DEFAULT '{"C11 / gcc","C++20 / g++","Pascal / fpc"}',
    submissions_download_allowed    boolean NOT NULL DEFAULT true,
    allow_questions                 boolean NOT NULL DEFAULT true,
    allow_user_tests                boolean NOT NULL DEFAULT true,
    allow_unofficial_submission_before_analysis_mode boolean NOT NULL DEFAULT false,
    block_hidden_participations     boolean NOT NULL DEFAULT false,
    allow_password_authentication   boolean NOT NULL DEFAULT true,
    allow_registration              boolean NOT NULL DEFAULT false,
    ip_restriction                  boolean NOT NULL DEFAULT true,
    ip_autologin                    boolean NOT NULL DEFAULT false,
    -- Contest tokens (combined with the task tokens).
    token_mode                      text NOT NULL DEFAULT 'infinite'
                                    CHECK (token_mode IN ('disabled', 'finite', 'infinite')),
    token_max_number                integer CHECK (token_max_number > 0),
    token_min_interval              interval NOT NULL DEFAULT '0 seconds' CHECK (token_min_interval >= '0 seconds'),
    token_gen_initial               integer NOT NULL DEFAULT 2 CHECK (token_gen_initial >= 0),
    token_gen_number                integer NOT NULL DEFAULT 2 CHECK (token_gen_number >= 0),
    token_gen_interval              interval NOT NULL DEFAULT '30 minutes' CHECK (token_gen_interval > '0 seconds'),
    token_gen_max                   integer CHECK (token_gen_max > 0),
    -- Imported from CMS; presentation uses the server timezone (D6).
    timezone                        text,
    max_submission_number           integer CHECK (max_submission_number > 0),
    max_user_test_number            integer CHECK (max_user_test_number > 0),
    min_submission_interval         interval CHECK (min_submission_interval > '0 seconds'),
    min_submission_interval_grace_period interval CHECK (min_submission_interval_grace_period > '0 seconds'),
    min_user_test_interval          interval CHECK (min_user_test_interval > '0 seconds'),
    score_precision                 integer NOT NULL DEFAULT 0 CHECK (score_precision >= 0),
    -- References groups: the foreign key is added after that table.
    main_group_id                   integer,
    CHECK (token_gen_initial <= token_gen_max)
);

-- A group of participants of a contest with its own times (cms/db/user.py).
-- Phases: before start, running, after stop, analysis, over.
CREATE TABLE groups (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             text NOT NULL,
    start            timestamptz NOT NULL DEFAULT '2000-01-01 00:00:00+00',
    stop             timestamptz NOT NULL DEFAULT '2100-01-01 00:00:00+00',
    analysis_enabled boolean NOT NULL DEFAULT false,
    analysis_start   timestamptz NOT NULL DEFAULT '2100-01-01 00:00:00+00',
    analysis_stop    timestamptz NOT NULL DEFAULT '2100-01-01 00:00:00+00',
    -- Maximum contest time of each participant (USACO-like windows).
    per_user_time    interval CHECK (per_user_time >= '0 seconds'),
    contest_id       integer NOT NULL REFERENCES contests (id) ON UPDATE CASCADE ON DELETE CASCADE,
    UNIQUE (contest_id, name),
    -- Target of participations_group_id_contest_id_fkey.
    UNIQUE (id, contest_id),
    CHECK (start <= stop),
    CHECK (stop <= analysis_start),
    CHECK (analysis_start <= analysis_stop)
);

ALTER TABLE contests ADD CONSTRAINT fk_contest_main_group_id
    FOREIGN KEY (main_group_id) REFERENCES groups (id) ON UPDATE CASCADE ON DELETE SET NULL;

-- Deleting a group (ON DELETE SET NULL) looks up the contests whose main group it is.
CREATE INDEX ix_contests_main_group_id ON contests (main_group_id);

-- A message from the contest managers to every contestant.
CREATE TABLE announcements (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp  timestamptz NOT NULL,
    subject    text NOT NULL,
    text       text NOT NULL,
    contest_id integer NOT NULL REFERENCES contests (id) ON UPDATE CASCADE ON DELETE CASCADE,
    -- Author; kept (as NULL) when the admin is deleted.
    admin_id   integer REFERENCES admins (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- The announcements of a contest (contestant and admin communication pages).
CREATE INDEX ix_announcements_contest_id ON announcements (contest_id);
-- Deleting an admin (ON DELETE SET NULL) looks up their announcements.
CREATE INDEX ix_announcements_admin_id ON announcements (admin_id);

-- A person who can take part in contests.
CREATE TABLE users (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name          text NOT NULL,
    last_name           text NOT NULL,
    username            text NOT NULL UNIQUE CHECK (username ~ '^[A-Za-z0-9_-]+$'),
    -- "<method>:<string>" as in admins.authentication. CMS generates a
    -- random password when none is given; here the code does.
    password            text NOT NULL,
    email               text,
    -- Imported from CMS; presentation uses the server timezone (D6).
    timezone            text,
    -- Statement languages to highlight, most preferred first.
    preferred_languages text[] NOT NULL DEFAULT '{}'
);

-- A team (e.g. a country delegation); only shown in the ranking.
CREATE TABLE teams (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (code ~ '^[A-Za-z0-9_-]+$'),
    name text NOT NULL
);

-- A user taking part in a contest.
CREATE TABLE participations (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Subnets the participant may connect from; NULL disables the IP
    -- lock, an empty array forbids every address.
    ip            cidr[],
    -- When the participant started their window (per_user_time).
    starting_time timestamptz,
    delay_time    interval NOT NULL DEFAULT '0 seconds' CHECK (delay_time >= '0 seconds'),
    extra_time    interval NOT NULL DEFAULT '0 seconds' CHECK (extra_time >= '0 seconds'),
    -- Overrides users.password for this contest when not NULL.
    password      text,
    -- Not shown in public rankings.
    hidden        boolean NOT NULL DEFAULT false,
    -- Exempt from contest times and submission limits.
    unrestricted  boolean NOT NULL DEFAULT false,
    contest_id    integer NOT NULL REFERENCES contests (id) ON UPDATE CASCADE ON DELETE CASCADE,
    user_id       integer NOT NULL REFERENCES users (id) ON UPDATE CASCADE ON DELETE CASCADE,
    group_id      integer NOT NULL REFERENCES groups (id) ON UPDATE CASCADE ON DELETE CASCADE,
    team_id       integer REFERENCES teams (id) ON UPDATE CASCADE ON DELETE SET NULL,
    -- The group belongs to the same contest.
    FOREIGN KEY (group_id, contest_id) REFERENCES groups (id, contest_id),
    UNIQUE (contest_id, user_id)
);

-- The contests of a user (login, contest list) and ON DELETE CASCADE from users.
CREATE INDEX ix_participations_user_id ON participations (user_id);
-- The participants of a group and ON DELETE CASCADE from groups.
CREATE INDEX ix_participations_group_id ON participations (group_id);

-- A private message from the contest managers to one participant.
CREATE TABLE messages (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp        timestamptz NOT NULL,
    subject          text NOT NULL,
    text             text NOT NULL,
    participation_id integer NOT NULL REFERENCES participations (id) ON UPDATE CASCADE ON DELETE CASCADE,
    admin_id         integer REFERENCES admins (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- The messages of a participant (communication page).
CREATE INDEX ix_messages_participation_id ON messages (participation_id);
-- Deleting an admin (ON DELETE SET NULL) looks up their messages.
CREATE INDEX ix_messages_admin_id ON messages (admin_id);

-- A question from a participant and its answer.
CREATE TABLE questions (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_timestamp timestamptz NOT NULL,
    subject            text NOT NULL,
    text               text NOT NULL,
    reply_timestamp    timestamptz,
    ignored            boolean NOT NULL DEFAULT false,
    reply_subject      text,
    reply_text         text,
    participation_id   integer NOT NULL REFERENCES participations (id) ON UPDATE CASCADE ON DELETE CASCADE,
    -- Last admin who answered, ignored or claimed the question.
    admin_id           integer REFERENCES admins (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- The questions of a participant (communication pages).
CREATE INDEX ix_questions_participation_id ON questions (participation_id);
-- Deleting an admin (ON DELETE SET NULL) looks up their questions.
CREATE INDEX ix_questions_admin_id ON questions (admin_id);

-- A task (cms/db/task.py); it may exist without a contest.
CREATE TABLE tasks (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Position in the contest.
    num                     integer,
    contest_id              integer REFERENCES contests (id) ON UPDATE CASCADE ON DELETE CASCADE,
    name                    text NOT NULL UNIQUE CHECK (name ~ '^[A-Za-z0-9_-]+$'),
    title                   text NOT NULL,
    -- Files to submit; "%l" stands for the language extension.
    submission_format       text[] NOT NULL DEFAULT '{}'
                            CHECK (array_to_string(submission_format, '') ~ '^[A-Za-z0-9_.%-]*$'
                                   AND array_to_string(submission_format, ',') ~ '^([A-Za-z0-9_.-]+(.%l)?(,|$))*$'
                                   AND '.' <> ALL (submission_format)
                                   AND '..' <> ALL (submission_format)),
    -- Statement languages highlighted to every participant.
    primary_statements      text[] NOT NULL DEFAULT '{}',
    -- NULL: the languages of the contest.
    allowed_languages       text[],
    -- Task tokens (combined with the contest tokens).
    token_mode              text NOT NULL DEFAULT 'disabled'
                            CHECK (token_mode IN ('disabled', 'finite', 'infinite')),
    token_max_number        integer CHECK (token_max_number > 0),
    token_min_interval      interval NOT NULL DEFAULT '0 seconds' CHECK (token_min_interval >= '0 seconds'),
    token_gen_initial       integer NOT NULL DEFAULT 2 CHECK (token_gen_initial >= 0),
    token_gen_number        integer NOT NULL DEFAULT 2 CHECK (token_gen_number >= 0),
    token_gen_interval      interval NOT NULL DEFAULT '30 minutes' CHECK (token_gen_interval > '0 seconds'),
    token_gen_max           integer CHECK (token_gen_max > 0),
    max_submission_number   integer CHECK (max_submission_number > 0),
    max_user_test_number    integer CHECK (max_user_test_number > 0),
    min_submission_interval interval CHECK (min_submission_interval > '0 seconds'),
    min_user_test_interval  interval CHECK (min_user_test_interval > '0 seconds'),
    feedback_level          text NOT NULL DEFAULT 'restricted'
                            CHECK (feedback_level IN ('full', 'restricted', 'oi_restricted')),
    score_precision         integer NOT NULL DEFAULT 0 CHECK (score_precision >= 0),
    score_mode              text NOT NULL DEFAULT 'max_tokened_last'
                            CHECK (score_mode IN ('max_tokened_last', 'max', 'max_subtask')),
    -- Dataset used for scoring; the foreign key (fk_active_dataset_id) is
    -- added after the datasets table.
    active_dataset_id       integer,
    UNIQUE (contest_id, num),
    UNIQUE (contest_id, name),
    CHECK (token_gen_initial <= token_gen_max)
);

-- One translation of the statement of a task (PDF).
CREATE TABLE statements (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id  integer NOT NULL REFERENCES tasks (id) ON UPDATE CASCADE ON DELETE CASCADE,
    -- Language code, e.g. "en" or "es_MX".
    language text NOT NULL,
    digest   text NOT NULL CHECK (digest ~ '^([0-9a-f]{64}|x)$'),
    UNIQUE (task_id, language)
);

-- A file given to the contestants with the statement.
CREATE TABLE attachments (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id  integer NOT NULL REFERENCES tasks (id) ON UPDATE CASCADE ON DELETE CASCADE,
    filename text NOT NULL CHECK (filename ~ '^[A-Za-z0-9_.-]+$' AND filename NOT IN ('.', '..')),
    digest   text NOT NULL CHECK (digest ~ '^([0-9a-f]{64}|x)$'),
    UNIQUE (task_id, filename)
);

-- A version of the judging data of a task: limits, task and score types,
-- managers and testcases.
CREATE TABLE datasets (
    id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id               integer NOT NULL REFERENCES tasks (id) ON UPDATE CASCADE ON DELETE CASCADE,
    description           text NOT NULL,
    -- Judged in the background together with the active dataset.
    autojudge             boolean NOT NULL DEFAULT false,
    -- Seconds and bytes, per testcase.
    time_limit            double precision CHECK (time_limit > 0),
    memory_limit          bigint
                          CONSTRAINT datasets_memory_limit_check CHECK (memory_limit > 0)
                          CONSTRAINT datasets_memory_limit_check1 CHECK (mod(memory_limit, 1048576) = 0),
    task_type             text NOT NULL,
    task_type_parameters  jsonb NOT NULL,
    score_type            text NOT NULL,
    score_type_parameters jsonb NOT NULL,
    UNIQUE (task_id, description),
    -- Target of fk_active_dataset_id.
    UNIQUE (id, task_id)
);

-- The active dataset belongs to the task. MATCH SIMPLE: not checked while
-- active_dataset_id is NULL. Deleting the active dataset is rejected (NO
-- ACTION), so a wrong request cannot wipe the official results of a task
-- (its submission_results, evaluations, executables) mid-contest; deleting
-- the task still removes it with the task row in the same statement.
ALTER TABLE tasks ADD CONSTRAINT fk_active_dataset_id
    FOREIGN KEY (id, active_dataset_id) REFERENCES datasets (task_id, id)
    ON UPDATE CASCADE;

-- A file needed to compile or evaluate (grader, checker, manager, header).
CREATE TABLE managers (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id integer NOT NULL REFERENCES datasets (id) ON UPDATE CASCADE ON DELETE CASCADE,
    filename   text NOT NULL CHECK (filename ~ '^[A-Za-z0-9_.-]+$' AND filename NOT IN ('.', '..')),
    digest     text NOT NULL CHECK (digest ~ '^([0-9a-f]{64}|x)$'),
    UNIQUE (dataset_id, filename)
);

-- One testcase of a dataset.
CREATE TABLE testcases (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id integer NOT NULL REFERENCES datasets (id) ON UPDATE CASCADE ON DELETE CASCADE,
    codename   text NOT NULL CHECK (codename ~ '^[A-Za-z0-9_-]+$'),
    -- Its outcome is shown to the contestant without playing a token.
    public     boolean NOT NULL DEFAULT false,
    input      text NOT NULL CHECK (input ~ '^([0-9a-f]{64}|x)$'),
    output     text NOT NULL CHECK (output ~ '^([0-9a-f]{64}|x)$'),
    UNIQUE (dataset_id, codename)
);

-- A submission (cms/db/submission.py).
CREATE TABLE submissions (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Random number in [0, 2^63) chosen by the code, unique per
    -- participation; contestants see it instead of id.
    opaque_id        bigint NOT NULL,
    participation_id integer NOT NULL REFERENCES participations (id) ON UPDATE CASCADE ON DELETE CASCADE,
    task_id          integer NOT NULL REFERENCES tasks (id) ON UPDATE CASCADE ON DELETE CASCADE,
    timestamp        timestamptz NOT NULL,
    -- NULL when not applicable (e.g. output-only tasks).
    language         text,
    -- Comment of an admin.
    comment          text NOT NULL DEFAULT '',
    -- Unofficial submissions do not count for the score.
    official         boolean NOT NULL DEFAULT true,
    CONSTRAINT participation_opaque_unique UNIQUE (participation_id, opaque_id)
);

-- A contestant's submissions to a task, by time (task submissions page,
-- per-task limits at submit time); participation_opaque_unique already
-- serves lookups by participation_id alone (CMS ix_submissions_participation_id).
CREATE INDEX ix_submissions_participation_id_task_id ON submissions (participation_id, task_id, timestamp);
-- The submissions of a task, newest first (admin, reevaluation) and ON DELETE CASCADE from tasks.
CREATE INDEX ix_submissions_task_id ON submissions (task_id, timestamp);

-- One submitted file.
CREATE TABLE files (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id integer NOT NULL REFERENCES submissions (id) ON UPDATE CASCADE ON DELETE CASCADE,
    filename      text NOT NULL CHECK (filename ~ '^[A-Za-z0-9_.-]+(.%l)?$' AND filename NOT IN ('.', '..')),
    digest        text NOT NULL CHECK (digest ~ '^([0-9a-f]{64}|x)$'),
    UNIQUE (submission_id, filename)
);

-- A token played on a submission (at most one).
CREATE TABLE tokens (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id integer NOT NULL UNIQUE REFERENCES submissions (id) ON UPDATE CASCADE ON DELETE CASCADE,
    timestamp     timestamptz NOT NULL DEFAULT now()
);

-- The compilation, evaluation and score of a submission on one dataset.
-- A missing row means "compiling".
CREATE TABLE submission_results (
    submission_id               integer NOT NULL REFERENCES submissions (id) ON UPDATE CASCADE ON DELETE CASCADE,
    dataset_id                  integer NOT NULL REFERENCES datasets (id) ON UPDATE CASCADE ON DELETE CASCADE,
    -- NULL: not compiled yet.
    compilation_outcome         text CHECK (compilation_outcome IN ('ok', 'fail')),
    -- A format string followed by its arguments, for translation.
    compilation_text            text[] NOT NULL DEFAULT '{}',
    compilation_tries           integer NOT NULL DEFAULT 0,
    compilation_stdout          text,
    compilation_stderr          text,
    compilation_time            double precision,
    compilation_wall_clock_time double precision,
    compilation_memory          bigint,
    compilation_shard           integer,
    compilation_sandbox_paths   text[],
    compilation_sandbox_digests text[],
    -- NULL: not evaluated yet.
    evaluation_outcome          text CHECK (evaluation_outcome IN ('ok')),
    evaluation_tries            integer NOT NULL DEFAULT 0,
    -- The score fields are NULL until scored.
    score                       double precision,
    score_details               jsonb,
    -- When it was scored for the first time.
    scored_at                   timestamptz,
    public_score                double precision,
    public_score_details        jsonb,
    ranking_score_details       text[],
    PRIMARY KEY (submission_id, dataset_id)
);

-- All the results of a dataset (scoring, rankings, dataset comparison) and
-- ON DELETE CASCADE from datasets; the primary key starts with submission_id.
CREATE INDEX ix_submission_results_dataset_id ON submission_results (dataset_id);

-- A file produced by compiling a submission for a dataset.
CREATE TABLE executables (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id integer NOT NULL REFERENCES submissions (id) ON UPDATE CASCADE ON DELETE CASCADE,
    dataset_id    integer NOT NULL REFERENCES datasets (id) ON UPDATE CASCADE ON DELETE CASCADE,
    filename      text NOT NULL CHECK (filename ~ '^[A-Za-z0-9_.-]+$' AND filename NOT IN ('.', '..')),
    digest        text NOT NULL CHECK (digest ~ '^([0-9a-f]{64}|x)$'),
    FOREIGN KEY (submission_id, dataset_id) REFERENCES submission_results (submission_id, dataset_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    UNIQUE (submission_id, dataset_id, filename)
);

-- ON DELETE CASCADE from datasets (the unique key starts with submission_id).
CREATE INDEX ix_executables_dataset_id ON executables (dataset_id);

-- The outcome of a submission on one testcase.
CREATE TABLE evaluations (
    id                         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id              integer NOT NULL REFERENCES submissions (id) ON UPDATE CASCADE ON DELETE CASCADE,
    dataset_id                 integer NOT NULL REFERENCES datasets (id) ON UPDATE CASCADE ON DELETE CASCADE,
    testcase_id                integer NOT NULL REFERENCES testcases (id) ON UPDATE CASCADE ON DELETE CASCADE,
    -- Usually a number in [0, 1]; the score type turns it into points.
    outcome                    text,
    -- Message for the contestant: a format string and its arguments.
    text                       text[] NOT NULL DEFAULT '{}',
    -- Message for the admins.
    admin_text                 text,
    execution_time             double precision,
    execution_wall_clock_time  double precision,
    execution_memory           bigint,
    evaluation_shard           integer,
    evaluation_sandbox_paths   text[],
    evaluation_sandbox_digests text[],
    FOREIGN KEY (submission_id, dataset_id) REFERENCES submission_results (submission_id, dataset_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    -- Also serves "the evaluations of a submission on a dataset".
    UNIQUE (submission_id, dataset_id, testcase_id)
);

-- ON DELETE CASCADE from datasets (the unique key starts with submission_id).
CREATE INDEX ix_evaluations_dataset_id ON evaluations (dataset_id);
-- ON DELETE CASCADE from testcases (editing a dataset) and per-testcase statistics.
CREATE INDEX ix_evaluations_testcase_id ON evaluations (testcase_id);

-- A test run requested by a contestant on their own input
-- (cms/db/usertest.py).
CREATE TABLE user_tests (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participation_id integer NOT NULL REFERENCES participations (id) ON UPDATE CASCADE ON DELETE CASCADE,
    task_id          integer NOT NULL REFERENCES tasks (id) ON UPDATE CASCADE ON DELETE CASCADE,
    timestamp        timestamptz NOT NULL,
    language         text,
    input            text NOT NULL CHECK (input ~ '^([0-9a-f]{64}|x)$')
);

-- A contestant's tests of a task, by time (testing page, per-task limits);
-- also lookups by participation_id alone (CMS ix_user_tests_participation_id)
-- and ON DELETE CASCADE from participations.
CREATE INDEX ix_user_tests_participation_id_task_id ON user_tests (participation_id, task_id, timestamp);
-- The tests of a task (admin) and ON DELETE CASCADE from tasks.
CREATE INDEX ix_user_tests_task_id ON user_tests (task_id);

-- One file submitted with a user test.
CREATE TABLE user_test_files (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_test_id integer NOT NULL REFERENCES user_tests (id) ON UPDATE CASCADE ON DELETE CASCADE,
    filename     text NOT NULL CHECK (filename ~ '^[A-Za-z0-9_.-]+(.%l)?$' AND filename NOT IN ('.', '..')),
    digest       text NOT NULL CHECK (digest ~ '^([0-9a-f]{64}|x)$'),
    UNIQUE (user_test_id, filename)
);

-- A manager (grader…) submitted with a user test.
CREATE TABLE user_test_managers (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_test_id integer NOT NULL REFERENCES user_tests (id) ON UPDATE CASCADE ON DELETE CASCADE,
    filename     text NOT NULL CHECK (filename ~ '^[A-Za-z0-9_.-]+$' AND filename NOT IN ('.', '..')),
    digest       text NOT NULL CHECK (digest ~ '^([0-9a-f]{64}|x)$'),
    UNIQUE (user_test_id, filename)
);

-- The compilation and execution of a user test on one dataset. Unlike
-- submission_results, CMS declares the outcomes as plain strings.
CREATE TABLE user_test_results (
    user_test_id                integer NOT NULL REFERENCES user_tests (id) ON UPDATE CASCADE ON DELETE CASCADE,
    -- Deleting a dataset scans this small table: no index on dataset_id.
    dataset_id                  integer NOT NULL REFERENCES datasets (id) ON UPDATE CASCADE ON DELETE CASCADE,
    output                      text CHECK (output ~ '^([0-9a-f]{64}|x)$'),
    compilation_outcome         text,
    compilation_text            text[] NOT NULL DEFAULT '{}',
    compilation_tries           integer NOT NULL DEFAULT 0,
    compilation_stdout          text,
    compilation_stderr          text,
    compilation_time            double precision,
    compilation_wall_clock_time double precision,
    compilation_memory          bigint,
    compilation_shard           integer,
    compilation_sandbox_paths   text[],
    compilation_sandbox_digests text[],
    evaluation_outcome          text,
    evaluation_text             text[] NOT NULL DEFAULT '{}',
    evaluation_tries            integer NOT NULL DEFAULT 0,
    execution_time              double precision,
    execution_wall_clock_time   double precision,
    execution_memory            bigint,
    evaluation_shard            integer,
    evaluation_sandbox_paths    text[],
    evaluation_sandbox_digests  text[],
    PRIMARY KEY (user_test_id, dataset_id)
);

-- A file produced by compiling a user test.
CREATE TABLE user_test_executables (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_test_id integer NOT NULL REFERENCES user_tests (id) ON UPDATE CASCADE ON DELETE CASCADE,
    dataset_id   integer NOT NULL REFERENCES datasets (id) ON UPDATE CASCADE ON DELETE CASCADE,
    filename     text NOT NULL CHECK (filename ~ '^[A-Za-z0-9_.-]+$' AND filename NOT IN ('.', '..')),
    digest       text NOT NULL CHECK (digest ~ '^([0-9a-f]{64}|x)$'),
    FOREIGN KEY (user_test_id, dataset_id) REFERENCES user_test_results (user_test_id, dataset_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    UNIQUE (user_test_id, dataset_id, filename)
);

-- ON DELETE CASCADE from datasets (the unique key starts with user_test_id).
CREATE INDEX ix_user_test_executables_dataset_id ON user_test_executables (dataset_id);

-- Fork addition: who changed what in the administration (R6.6). Rows are
-- only appended. admin_id and contest_id become NULL when the admin or the
-- contest is deleted; details keeps what is needed to read the row then
-- (names, old and new values).
CREATE TABLE audit_log (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          timestamptz NOT NULL DEFAULT now(),
    admin_id    integer REFERENCES admins (id) ON UPDATE CASCADE ON DELETE SET NULL,
    -- What happened, e.g. "task.update", "submission.reevaluate".
    action      text NOT NULL CHECK (action <> ''),
    -- What it happened to: a table-like name ("task", "dataset", …) and,
    -- when it has one, the id.
    target_type text NOT NULL CHECK (target_type <> ''),
    target_id   bigint,
    contest_id  integer REFERENCES contests (id) ON UPDATE CASCADE ON DELETE SET NULL,
    details     jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(details) = 'object'),
    -- Address the request came from.
    ip          inet
);

-- The whole log newest first (ORDER BY at DESC, id DESC) and time ranges ("what happened at 10:05?").
CREATE INDEX ix_audit_log_at ON audit_log (at);
-- The log of a contest newest first, and ON DELETE SET NULL from contests.
CREATE INDEX ix_audit_log_contest_id ON audit_log (contest_id, at);
-- The history of one object ("who changed task 7?") newest first.
CREATE INDEX ix_audit_log_target ON audit_log (target_type, target_id, at);
-- The actions of one admin newest first, and ON DELETE SET NULL from admins.
CREATE INDEX ix_audit_log_admin_id ON audit_log (admin_id, at);
