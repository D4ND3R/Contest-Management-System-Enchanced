// webTranslation adapts a language of internal/web, as the sites do.
type webTranslation struct{ l *web.Lang }

func (t webTranslation) T(msgid string) string          { return t.l.T(msgid) }
func (t webTranslation) FormatDecimal(x float64) string { return t.l.Locale.FormatDecimal(x) }
func (t webTranslation) FormatDuration(s float64) string {
	return t.l.Locale.FormatDuration(s, "short")
}
func (t webTranslation) FormatSize(n int64) string          { return t.l.Locale.FormatSize(n) }
func (t webTranslation) FormatStatusText(s []string) string { return web.FormatStatusText(s, t.l) }

func testLanguages(t *testing.T) *web.Languages {
	t.Helper()
	ls, err := web.NewLanguages(web.LanguagesOptions{
		Catalogs: locale.FS,
		Domains:  []string{locale.DomainContest},
		Locale:   func(code string) web.Locale { return l10n.Get(code) },
	})
	if err != nil {
		t.Fatal(err)
	}
	return ls
}

type htmlGolden struct {
	Name          string          `json:"name"`
	ScoreType     string          `json:"score_type"`
	Details       json.RawMessage `json:"details"`
	FeedbackLevel FeedbackLevel   `json:"feedback_level"`
	Lang          string          `json:"lang"`
	HTML          string          `json:"html"`
}

// TestHTMLDetailsGolden compares the HTML of the details with what CMS
// renders for the same details (testdata/details_html_golden.json.gz,
// generated by testdata/gen_details_html.py with the original CMS).
func TestHTMLDetailsGolden(t *testing.T) {
	f, err := os.Open("testdata/details_html_golden.json.gz")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	zr, err := gzip.NewReader(f)
	if err != nil {
		t.Fatal(err)
	}
	b, err := io.ReadAll(zr)
	if err != nil {
		t.Fatal(err)
	}
	var cases []htmlGolden
	if err := json.Unmarshal(b, &cases); err != nil {
		t.Fatal(err)
	}
	if len(cases) < 200 {
		t.Fatalf("only %d cases", len(cases))
	}
	ls := testLanguages(t)
	compared, unavailable := 0, 0
	for _, c := range cases {
		lang := ls.Get(c.Lang)
		if lang == nil {
			t.Fatalf("%s: no language %s", c.Name, c.Lang)
		}
		tr := webTranslation{lang}
		st := &fakeType{grouped: c.ScoreType != NameSum}
		got := string(HTMLDetails(st, c.Details, c.FeedbackLevel, tr))
		if c.HTML == "Score details temporarily unavailable." && string(c.Details) != "null" {
			// CMS fails on the public details of a subtask with private
			// testcases (they have no score); we show it as N/A.
			unavailable++
			if !strings.Contains(got, `<div class="subtask undefined">`) {
				t.Errorf("%s: want the subtasks without score as undefined, got\n%s", c.Name, got)
			}
			continue
		}
		compared++
		if got != c.HTML {
			t.Errorf("%s differs from CMS at %s", c.Name, firstLineDiff(c.HTML, got))
		}
	}
	t.Logf("%d cases equal to CMS, %d where CMS shows no details", compared, unavailable)
}

// fakeType is a ScoreType whose JSONDetails is the one of its kind.
type fakeType struct {
	ScoreType
	grouped bool
}

func (f *fakeType) JSONDetails(raw json.RawMessage, level FeedbackLevel) (*Details, error) {
	return jsonDetails(raw, level, f.grouped)
}

func firstLineDiff(want, got string) string {
	w, g := strings.Split(want, "\n"), strings.Split(got, "\n")
	for i := 0; i < len(w) || i < len(g); i++ {
		var a, b string
		if i < len(w) {
			a = w[i]
		}
		if i < len(g) {
			b = g[i]
		}
		if a != b {
			return "line " + strconv.Itoa(i+1) + ":\nCMS:  " + a + "\nours: " + b
		}
	}
	return ""
}

// TestRenderDetailsNil writes the message of CMS for NULL details.
func TestRenderDetailsNil(t *testing.T) {
	ls := testLanguages(t)
	var b bytes.Buffer
	if err := RenderDetails(&b, nil, webTranslation{ls.Get("es")}); err != nil {
		t.Fatal(err)
	}
	if want := ls.Get("es").T(MsgUnavailable); b.String() != want {
		t.Errorf("got %q, want %q", b.String(), want)
	}
	st, err := New(NameSum, json.RawMessage(`10`), map[string]bool{"a": true}, 0)
	if err != nil {
		t.Fatal(err)
	}
	en := webTranslation{ls.Get("en")}
	for _, raw := range []string{`null`, `{"a": 1}`, `[1, 2]`, `"x"`} {
		if got := HTMLDetails(st, json.RawMessage(raw), FeedbackFull, en); got != MsgUnavailable {
			t.Errorf("%s: got %q", raw, got)
		}
	}
	if got := FormatScore(12.5, 100, webTranslation{ls.Get("es")}); got != "12,5 / 100" {
		t.Errorf("FormatScore: %q", got)
	}
}

// TestRenderDetailsEscapes checks that the values of the details are
// escaped (testcase names, arguments of the evaluation texts).
func TestRenderDetailsEscapes(t *testing.T) {
	ls := testLanguages(t)
	st, err := New(NameGroupMin, json.RawMessage(`[[100, 1]]`), map[string]bool{"a": true}, 0)
	if err != nil {
		t.Fatal(err)
	}
	raw := `[{"idx": 0, "score_fraction": 0, "score": 0, "max_score": 100, "testcases": [
		{"idx": "a", "outcome": "<script>x</script>", "text": ["Evaluation didn't produce file %s", "<img src=x onerror=alert(1)>"],
		 "show_in_restricted_feedback": true, "show_in_oi_restricted_feedback": true}]}]`
	got := string(HTMLDetails(st, json.RawMessage(raw), FeedbackFull, webTranslation{ls.Get("en")}))
	if strings.Contains(got, "<script>") || strings.Contains(got, "<img") {
		t.Errorf("not escaped:\n%s", got)
	}
	if !strings.Contains(got, "&lt;img src=x onerror=alert(1)&gt;") {
		t.Errorf("missing escaped text:\n%s", got)
	}
}
